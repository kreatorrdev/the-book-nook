import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { rm } from "node:fs/promises";
import path from "node:path";
import { eq } from "drizzle-orm";

const root = path.resolve(".data/tests");
const directory = path.resolve(root, randomUUID());
process.env.BOOK_NOOK_DATA_DIR = directory;
delete process.env.DATABASE_URL;
process.env.BETTER_AUTH_URL = "http://localhost:3000";
process.env.BETTER_AUTH_SECRET = randomUUID() + randomUUID();
process.env.ALLOW_LOCAL_DATABASE = "1";
let checks = 0;
const check = (condition: unknown, message: string) => { assert.ok(condition, message); checks++; console.log(`PASS ${message}`); };
async function main() {
  const { getAuth } = await import("../src/lib/auth");
  const { getDb, closeDb } = await import("../src/db");
  const schema = await import("../src/db/schema");
  const reader = await import("../src/app/api/reader/route");
  const admin = await import("../src/app/api/admin/route");
  const auth = await getAuth();
  const origin = "http://localhost:3000";
  const password = "Private-reading-test-2026!";
  async function authCall(endpoint: string, body: unknown, cookie = "") {
    const response = await auth.handler(new Request(origin + "/api/auth/" + endpoint, { method: "POST", headers: { origin, "content-type": "application/json", cookie }, body: JSON.stringify(body) }));
    const json = await response.json();
    return { response, json, cookie: response.headers.getSetCookie().map(c => c.split(";")[0]).join("; ") };
  }
  const a = await authCall("sign-up/email", { email: "alice@example.test", password, name: "Alice", role: "admin" });
  const b = await authCall("sign-up/email", { email: "bea@example.test", password, name: "Bea" });
  const editor = await authCall("sign-up/email", { email: "editor@example.test", password, name: "Editor" });
  check(a.response.ok && b.response.ok && editor.response.ok, "accounts use real persistent authentication");
  check(a.json.user.role === "reader", "reader cannot assign an administrator role at sign-up");
  const db = await getDb();
  const snapshot = async (cookie = "") => (await reader.GET(new Request(origin + "/api/reader", { headers: { cookie } }))).json();
  const write = async (cookie: string, body: unknown, requestOrigin = origin) => {
    const response = await reader.POST(new Request(origin + "/api/reader", { method: "POST", headers: { origin: requestOrigin, cookie, "content-type": "application/json" }, body: JSON.stringify(body) }));
    return { response, json: await response.json() };
  };
  const edit = async (body: unknown, cookie = editor.cookie) => {
    const response = await admin.POST(new Request(origin + "/api/admin", { method: "POST", headers: { origin, cookie, "content-type": "application/json" }, body: JSON.stringify(body) }));
    return { response, json: await response.json() };
  };
  try {
    check(!(await write(a.cookie, { action: "publish-review", bookId: "walden", body: "A review before moderation is provisioned.", rating: 4, spoiler: false, publicConsent: true })).response.ok, "public publishing stays closed until moderation has an administrator");
    await db.update(schema.user).set({ role: "admin" }).where(eq(schema.user.id, editor.json.user.id));
    const guest = await snapshot();
    check(guest.books.length === 40 && guest.collections.length === 5, "curated guest catalog works without an external service");
    check(guest.shelves.length === 0 && guest.journals.length === 0 && !guest.reader, "guest responses contain no private records");
    check((await write("", { action: "library", bookId: "walden", status: "want" })).response.status === 401, "guest writes require authentication");
    check((await write(a.cookie, { action: "library", bookId: "walden", status: "want" }, "https://example.test")).response.status === 403, "cross-origin writes are rejected");
    let result = await write(a.cookie, { action: "library", bookId: "pride-and-prejudice", status: "reading", favorite: true, progress: 25 });
    check(result.response.ok && result.json.data.shelves[0].favorite, "favorite membership is independent of reading status");
    result = await write(a.cookie, { action: "library", bookId: "pride-and-prejudice", status: "reading", progress: 50, progressMode: "pages" });
    check(!result.response.ok, "unknown editions reject page progress");
    result = await write(a.cookie, { action: "library", bookId: "pride-and-prejudice", status: "reading", editionId: "walden-unspecified" });
    check(!result.response.ok, "an edition cannot belong to a different work");
    result = await write(a.cookie, { action: "library", bookId: "pride-and-prejudice", status: "reading", editionId: "pride-and-prejudice-penguin-2002", progress: 224, progressMode: "pages" });
    check(!result.response.ok, "edition changes with progress require explicit reset confirmation");
    result = await write(a.cookie, { action: "library", bookId: "pride-and-prejudice", status: "reading", editionId: "pride-and-prejudice-penguin-2002", progress: 224, progressMode: "pages", resetProgress: true });
    check(result.response.ok && result.json.data.shelves[0].progress === 224, "page progress uses the selected edition's known total");
    check(!(await write(a.cookie, { action: "library", bookId: "pride-and-prejudice", status: "reading", progress: 449, progressMode: "pages" })).response.ok, "out-of-range pages are rejected on the server");
    result = await write(a.cookie, { action: "library", bookId: "pride-and-prejudice", status: "reading", paused: true });
    check(result.response.ok && result.json.data.shelves[0].paused, "a reader can pause without marking a book finished");
    result = await write(a.cookie, { action: "save-journal", title: "A private thought", body: "This text is private and must not enter any public response.", bookId: "pride-and-prejudice" });
    check(result.response.ok, "a linked journal entry persists");
    const journal = result.json.data.journals[0];
    result = await write(b.cookie, { action: "save-journal", id: journal.id, version: journal.updatedAt, title: "Stolen entry", body: "An unauthorized edit", bookId: null });
    check(!result.response.ok, "another reader cannot edit an entry by guessing its ID");
    check(!(await write(b.cookie, { action: "delete-journal", id: journal.id })).response.ok, "another reader cannot delete a journal entry");
    check(!(await write(a.cookie, { action: "save-journal", id: journal.id, version: "2000-01-01T00:00:00.000Z", title: "A stale edit", body: "A stale browser window", bookId: null })).response.ok, "stale saves preserve the last saved journal content");
    check(!(await write(a.cookie, { action: "publish-review", bookId: "pride-and-prejudice", rating: 5, spoiler: true, body: "A thoughtful and surprisingly funny story about learning to listen." })).response.ok, "review publishing requires explicit public consent");
    result = await write(a.cookie, { action: "publish-review", bookId: "pride-and-prejudice", rating: 5, spoiler: true, body: "A thoughtful and surprisingly funny story about learning to listen.", publicConsent: true });
    check(result.response.ok, "a reader can deliberately publish a spoiler-marked review");
    const review = result.json.data.reviews[0];
    const visible = await snapshot(b.cookie);
    check(visible.journals.length === 0 && visible.shelves.length === 0 && visible.reviews[0].spoiler && !("userId" in visible.reviews[0]), "public reviews expose no journal, library, or owner IDs");
    check((await admin.GET(new Request(origin + "/api/admin", { headers: { cookie: a.cookie } }))).status === 403, "readers cannot access the moderation desk");
    check(!(await edit({ action: "moderate", id: review.id, hidden: true }, a.cookie)).response.ok, "readers cannot forge moderation writes");
    check((await write(b.cookie, { action: "report-review", id: review.id, reason: "This is a test report for the moderator." })).response.ok, "public reviews can be reported");
    let desk = await (await admin.GET(new Request(origin + "/api/admin", { headers: { cookie: editor.cookie } }))).json();
    check(desk.reports.length === 1 && !desk.reports[0].resolved, "administrators can see open review reports");
    check((await edit({ action: "moderate", id: review.id, hidden: true })).response.ok, "administrators can hide a public review");
    check((await snapshot()).reviews.length === 0, "hidden reviews disappear from guest responses");
    await write(a.cookie, { action: "publish-review", bookId: "pride-and-prejudice", rating: 4, spoiler: false, body: "An updated thoughtful review that should remain hidden until restored.", publicConsent: true });
    check((await snapshot()).reviews.length === 0, "editing a hidden review cannot bypass moderation");
    check((await edit({ action: "moderate", id: review.id, hidden: false })).response.ok && (await snapshot()).reviews.length === 1, "administrators can restore a review");
    check((await edit({ action: "resolve", id: desk.reports[0].id })).response.ok, "reports can be resolved");
    const pride = guest.books.find((book: { id: string }) => book.id === "pride-and-prejudice");
    await edit({ action: "book", ...pride, available: false });
    check(!(await snapshot()).books.some((book: { id: string }) => book.id === pride.id) && (await snapshot(a.cookie)).books.some((book: { id: string }) => book.id === pride.id), "unlisting a book keeps its metadata available to its existing reader");
    await edit({ action: "book", ...pride, available: true });
    const walden = guest.books.find((book: { id: string }) => book.id === "walden");
    check((await edit({ action: "book", ...walden, genre: "Nature", moods: ["Reflective", "Comforting"], description: walden.description + " An editorial update." })).response.ok, "administrators can edit catalog metadata and mood tags");
    const collection = guest.collections[0];
    check((await edit({ action: "collection", ...collection, description: collection.description + " A considered edit." })).response.ok, "administrators can edit collections");
    await write(a.cookie, { action: "remove-book", bookId: "pride-and-prejudice" });
    const retained = await snapshot(a.cookie);
    check(retained.shelves.length === 0 && retained.journals.length === 1 && retained.reviews.length === 1, "library removal retains journal entries and reviews");
    const login = await authCall("sign-in/email", { email: "alice@example.test", password });
    check(login.response.ok && (await snapshot(login.cookie)).journals.length === 1, "saved writing survives sign-in with a new session");
    const signedOut = await authCall("sign-out", {}, login.cookie);
    check(signedOut.response.ok && !(await snapshot(login.cookie)).reader, "sign-out revokes the server session");
    const deleted = await authCall("delete-user", { password }, a.cookie);
    check(deleted.response.ok && (await snapshot()).reviews.length === 0, "account deletion removes public reviews and private records");
    check((await db.select().from(schema.journals)).length === 0, "account deletion cascades to private journal rows");
    await db.insert(schema.shelves).values({ id: randomUUID(), userId: b.json.user.id, bookId: "walden", status: "want", favorite: true });
    await closeDb();
    const reopened = await getDb();
    const persisted = await reopened.select().from(schema.shelves).where(eq(schema.shelves.userId, b.json.user.id));
    check(persisted.length === 1 && persisted[0].favorite, "reader state survives closing and reopening the on-disk PostgreSQL database");
    console.log(`\n${checks} integration checks passed.`);
  } finally {
    await closeDb();
    if (!directory.startsWith(root + path.sep)) throw new Error("Unsafe test cleanup path");
    await rm(directory, { recursive: true, force: true });
  }
}
main().then(() => process.exit(0)).catch(error => { console.error(error); process.exit(1); });
